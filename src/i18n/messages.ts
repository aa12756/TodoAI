const catalogs: Record<Locale, Record<MessageKey, string>> = { zh, en }

export function t(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  let text = catalogs[locale][key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value))
    }
  }
  return text
}

export function priorityShort(locale: Locale, priority: TaskPriority): string {
  const map: Record<TaskPriority, MessageKey> = {
    0: 'priorityShortLow',
    1: 'priorityShortMid',
    2: 'priorityShortHigh'
  }
  return t(locale, map[priority])
}

export function filterLabel(locale: Locale, filter: TaskFilter): string {
  const map: Record<TaskFilter, MessageKey> = {
    all: 'filterAll',
    today: 'filterToday',
    this_week: 'filterThisWeek',
    next_week: 'filterNextWeek',
    this_month: 'filterThisMonth',
    overdue: 'filterOverdue',
    done: 'filterDone'
  }
  return t(locale, map[filter])
}

export function priorityLabel(locale: Locale, priority: TaskPriority): string {
  const map: Record<TaskPriority, MessageKey> = {
    0: 'priorityLow',
    1: 'priorityMid',
    2: 'priorityHigh'
  }
  return t(locale, map[priority])
}

export function statusLabel(locale: Locale, status: TaskStatus): string {
  return status === 'done' ? t(locale, 'statusDone') : t(locale, 'statusOpen')
}

/** 主进程返回的中文错误 → 按当前语言展示 */
export function localizeError(locale: Locale, message: string): string {
  const table: Record<string, MessageKey> = {
    标题不能为空: 'errTitleRequired',
    任务不存在: 'errTaskNotFound'
  }
  const key = table[message]
  return key ? t(locale, key) : message
}
